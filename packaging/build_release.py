#!/usr/bin/env python3
"""Build the OnlyLauncher release artifacts.

Sub-commands:

``icon``
    Render ``packaging/icons/onlylauncher-{256,512}.png`` and
    ``onlylauncher.ico`` from ``mcLaunch/images/vanilla.png`` (needs Pillow).

``onefile``
    Single self-extracting binary in ``build_out/onefile/``.

``appimage``
    ``onedir`` build, wrapped into an ``AppDir`` and squashed into
    ``build_out/OnlyLauncher-x86_64.AppImage``.

``wine-exe``
    Best effort Windows build: installs a Windows CPython and a portable Git
    inside a dedicated Wine prefix and runs the same spec there. Git is needed
    because ``portablemc`` is installed from the project fork on GitHub
    (``git+https://...``), and pip shells out to ``git`` to clone it. See
    ``build_windows_exe``.

Usage::

    python packaging/build_release.py icon
    python packaging/build_release.py appimage
    python packaging/build_release.py onefile
    python packaging/build_release.py wine-exe
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MC_DIR = ROOT / "mcLaunch"
SPEC = ROOT / "packaging" / "onlylauncher.spec"
OUT = ROOT / "build_out"
TOOLS = OUT / "tools"
ICONS = ROOT / "packaging" / "icons"

NAME = "OnlyLauncher"
ICON_SOURCE = MC_DIR / "images" / "vanilla.png"
APPIMAGETOOL_URL = (
    "https://github.com/AppImage/appimagetool/releases/download/continuous/"
    "appimagetool-x86_64.AppImage"
)
PYTHON_WIN_URL = (
    "https://www.python.org/ftp/python/3.12.10/python-3.12.10-amd64.exe"
)
#: The launcher depends on this fork (OptiFine/NeoForge patches), not on the
#: PyPI release. Used by ``clone_fork``.
PORTABLEMC_FORK = "https://github.com/pi-dev500/portablemc.git"
#: Runtime dependencies, installed in the Wine prefix for the Windows build.
#: ``portablemc`` MUST come from the fork: it carries the OptiFine/NeoForge
#: patches the launcher relies on. It is installed from GitHub, hence the Git
#: build dependency. ``psutil`` is imported by ``McOptions.py``.
WINDOWS_REQUIREMENTS = [
    "pyinstaller>=6.10",
    "requests",
    "beautifulsoup4",
    "lxml",
    "tkinterweb",
    "pillow",
    "psutil",
    "PyQt6",
    "PyQt6-WebEngine",
    "git+https://github.com/pi-dev500/portablemc.git",
]

#: Run by the Wine-hosted Python to verify (and repair) the PyInstaller
#: bootloader directory. PyInstaller computes ``site-packages/PyInstaller/
#: bootloader/<PLATFORM>`` and aborts with the opaque "does not include a
#: pre-compiled bootloader for your platform" message when that directory is
#: absent, without ever printing which path it tried. This script prints the
#: computed values, then copies any usable Windows bootloader to the expected
#: name, turning a dead end into a warning.
