def run(cmd, **kwargs):
    """Run a command, echoing it, and return the completed process."""
    printable = " ".join(str(part) for part in cmd)
    print(f"\n$ {printable}", flush=True)
    return subprocess.run([str(part) for part in cmd], check=True, **kwargs)


def download(url, destination):
    """Download ``url`` to ``destination`` unless it is already there."""
    destination = Path(destination)
    if destination.is_file() and destination.stat().st_size > 0:
        return destination
    destination.parent.mkdir(parents=True, exist_ok=True)
    print(f"Téléchargement de {url}", flush=True)
    with urllib.request.urlopen(url, timeout=120) as response, \
            open(destination, "wb") as handle:
        shutil.copyfileobj(response, handle)
    return destination


def clone_fork(destination=None):
    """Clone the portablemc fork on the build host; return the checkout.

    Cloning on the host is far more reliable than letting a Windows ``pip``
    shell out to a Windows ``git`` inside Wine. The resulting folder is then
    installed with ``pip install <folder>``, which needs no VCS at all.
    """
    destination = Path(destination) if destination else OUT / "fork" / "portablemc"
    if (destination / "portablemc" / "__init__.py").is_file():
        print(f"Fork déjà cloné : {destination.relative_to(ROOT)}")
        return destination
    if not shutil.which("git"):
        sys.exit("git est introuvable sur l'hôte : installe-le (pacman -S git).")
    if destination.exists():
        shutil.rmtree(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    run(["git", "clone", "--depth", "1", PORTABLEMC_FORK, destination])
    if not (destination / "portablemc" / "optifine.py").is_file():
        sys.exit(f"Le clone ne contient pas portablemc/optifine.py : {destination}")
    print(f"Fork prêt : {destination.relative_to(ROOT)}")
    return destination


def make_icons():
    """Render the PNG icons and the Windows .ico; return their paths."""
    try:
        from PIL import Image
    except ImportError:
        sys.exit("Pillow est requis pour générer les icônes : pip install pillow")

    if not ICON_SOURCE.is_file():
        sys.exit(f"Image source introuvable : {ICON_SOURCE}")
    ICONS.mkdir(parents=True, exist_ok=True)
    source = Image.open(ICON_SOURCE).convert("RGBA")
    sizes = (16, 24, 32, 48, 64, 128, 256)
    paths = {"ico": ICONS / "onlylauncher.ico"}
    for size in (256, 512):
        paths[str(size)] = ICONS / f"onlylauncher-{size}.png"
        source.resize((size, size), Image.LANCZOS).save(paths[str(size)])
    source.resize((256, 256), Image.LANCZOS).save(
        paths["ico"], format="ICO", sizes=[(s, s) for s in sizes])
    for path in paths.values():
        print(f"icône : {path.relative_to(ROOT)}")
    return paths


def build_pyinstaller(mode, console=True, icon=None, dist_name=None):
    """Run PyInstaller with the release spec; return the produced path."""
    dist_name = dist_name or mode
    env = dict(os.environ)
    env["ONLYLAUNCHER_MODE"] = mode
    env["ONLYLAUNCHER_NAME"] = NAME
    env["ONLYLAUNCHER_CONSOLE"] = "1" if console else "0"
    if icon:
        env["ONLYLAUNCHER_ICON"] = str(icon)
    distpath = OUT / dist_name
    run(
        [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
         "--distpath", distpath, "--workpath", OUT / "work", SPEC],
        cwd=ROOT, env=env,
    )
    return distpath / NAME


def make_appdir(bundle, icon_png):
    """Assemble the AppDir layout expected by appimagetool."""
    appdir = OUT / "AppDir"
    if appdir.exists():
        shutil.rmtree(appdir)
    bin_dir = appdir / "usr" / "bin"
    icons_dir = appdir / "usr" / "share" / "icons" / "hicolor" / "256x256" / "apps"
    apps_dir = appdir / "usr" / "share" / "applications"
    for directory in (bin_dir, icons_dir, apps_dir):
        directory.mkdir(parents=True, exist_ok=True)

    shutil.copytree(bundle, bin_dir, dirs_exist_ok=True)
    for relative in (Path("onlylauncher.desktop"), Path("AppRun")):
        target = appdir / relative
        target.write_text(DESKTOP if relative.suffix == ".desktop" else APPRUN,
                          encoding="utf-8")
        target.chmod(0o755)
    shutil.copy2(icon_png, appdir / "onlylauncher.png")
    shutil.copy2(icon_png, icons_dir / "onlylauncher.png")
    shutil.copy2(appdir / "onlylauncher.desktop", apps_dir / "onlylauncher.desktop")
    print(f"AppDir prêt : {appdir.relative_to(ROOT)}")
    return appdir


def get_appimagetool():
    """Return a usable appimagetool executable, downloading it if needed."""
    tool = TOOLS / "appimagetool-x86_64.AppImage"
    download(APPIMAGETOOL_URL, tool)
    tool.chmod(0o755)
    return tool


def make_appimage(appdir):
    """Squash the AppDir into ``build_out/OnlyLauncher-x86_64.AppImage``."""
    tool = get_appimagetool()
    target = OUT / f"{NAME}-x86_64.AppImage"
    if target.exists():
        target.unlink()
    env = dict(os.environ)
    env.setdefault("ARCH", "x86_64")
    env["APPIMAGE_EXTRACT_AND_RUN"] = "1"  # works without FUSE
    run([tool, "--no-appstream", appdir, target], cwd=ROOT, env=env)
    target.chmod(0o755)
    size = target.stat().st_size / (1024 * 1024)
    print(f"\nAppImage : {target} ({size:.0f} Mo)")
    return target


def build_appimage():
    """Build the onedir bundle and pack it as an AppImage."""
    icons = make_icons()
    bundle = build_pyinstaller("onedir", icon=icons["256"])
    appdir = make_appdir(bundle, icons["256"])
    return make_appimage(appdir)


def build_onefile():
    """Build the single-file Linux executable."""
    icons = make_icons()
    binary = build_pyinstaller("onefile", icon=icons["256"])
    if not binary.is_file():
        sys.exit(f"Binaire introuvable : {binary}")
    print(f"\nBinaire : {binary} "
          f"({binary.stat().st_size / (1024 * 1024):.0f} Mo)")
    return binary


def wine_env():
    """Return an environment pointing Wine at a dedicated 64-bit prefix."""
    prefix = OUT / "wineprefix"
    prefix.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["WINEPREFIX"] = str(prefix)
    env["WINEARCH"] = "win64"
    env["WINEDEBUG"] = "-all"
    return env


def install_windows_python(env):
    """Install a Windows CPython inside the Wine prefix; return its exe."""
    python_exe = Path(env["WINEPREFIX"]) / "drive_c" / "Python312" / "python.exe"
    if python_exe.is_file():
        return python_exe
    installer = download(PYTHON_WIN_URL, TOOLS / "python-3.12.10-amd64.exe")
    run(["wine", installer, "/quiet", "InstallAllUsers=0", "PrependPath=0",
         "Include_test=0", "Include_launcher=0", "Include_tcltk=1",
         r"TargetDir=C:\Python312"], env=env)
    if not python_exe.is_file():
        sys.exit(f"Python Windows non installé ({python_exe}).")
    return python_exe


def install_windows_requirements(python_exe, env, fork_dir):
    """Install the runtime dependencies into the Wine-hosted Python.

    ``portablemc`` comes from the project fork, which was cloned on the host by
    :func:`clone_fork` and is installed here as a local folder. This avoids
    asking a Windows ``pip`` to run ``git clone`` inside Wine: no Windows Git
    and no network round-trip from the prefix are needed.
    """
    run(["wine", python_exe, "-m", "pip", "install", "--upgrade", "pip"], env=env)
    requirements = [r for r in WINDOWS_REQUIREMENTS if "portablemc" not in r]
    run(["wine", python_exe, "-m", "pip", "install", *requirements], env=env)
    # Build isolation stays on: the fork is a poetry project, so pip must fetch
    # ``poetry-core`` itself. ``--no-deps`` skips its optional certifi extra.
    run(["wine", python_exe, "-m", "pip", "install", "--no-deps", str(fork_dir)],
        env=env)
    run(["wine", python_exe, "-c",
         "import portablemc.optifine as m; print('fork OK:', m.__file__)"], env=env)


def check_windows_bootloader(python_exe, env):
    """Verify the Wine-hosted PyInstaller has a Windows bootloader.

    PyInstaller looks for ``bootloader/<PLATFORM>/run[w].exe`` and aborts with
    a generic "no pre-compiled bootloader for your platform" message when the
    directory name does not match what it computed, which hides the real path.
    The probe prints those values and copies a compatible bootloader into
    place, so the build continues instead of failing with a dead end.
    """
    script = OUT / "probe_bootloader.py"
    script.write_text(PROBE_BOOTLOADER, encoding="utf-8")
    try:
        run(["wine", python_exe, script], env=env)
    except subprocess.CalledProcessError:
        sys.exit(
            "PyInstaller n'a aucun bootloader Windows exploitable dans le "
            "prefix Wine. Diagnostic : réinstalle-le avec\n"
            "  wine <python.exe> -m pip install --force-reinstall --no-cache-dir pyinstaller\n"
            "ou construis l'exe sur windows-latest (voir .github/workflows)."
        )


def build_windows_exe():
    """Build ``OnlyLauncher.exe`` under Wine (best effort, untested upstream)."""
    if not shutil.which("wine"):
        sys.exit("wine est introuvable : installe-le (pacman -S wine).")
    env = wine_env()
    icons = make_icons()
    fork_dir = clone_fork()
    python_exe = install_windows_python(env)
    install_windows_requirements(python_exe, env, fork_dir)
    check_windows_bootloader(python_exe, env)
    spec_env = dict(env)
    spec_env.update({
        "ONLYLAUNCHER_MODE": "onefile",
        "ONLYLAUNCHER_NAME": NAME,
        "ONLYLAUNCHER_CONSOLE": "0",
        "ONLYLAUNCHER_ICON": str(icons["ico"]),
    })
    run(["wine", python_exe, "-m", "PyInstaller", "--noconfirm", "--clean",
         "--distpath", OUT / "windows", "--workpath", OUT / "work-windows",
         SPEC], cwd=ROOT, env=spec_env)
    exe = OUT / "windows" / f"{NAME}.exe"
    if not exe.is_file():
        sys.exit(f"Échec : {exe} n'a pas été produit.")
    print(f"\nWindows : {exe} ({exe.stat().st_size / (1024 * 1024):.0f} Mo)")
    return exe


COMMANDS = {
    "icon": make_icons,
    "onefile": build_onefile,
    "appimage": build_appimage,
    "wine-exe": build_windows_exe,
}


def main(argv=None):
    """Parse the command line and run the requested build."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=sorted(COMMANDS))
    args = parser.parse_args(argv)
    OUT.mkdir(parents=True, exist_ok=True)
    COMMANDS[args.command]()
    return 0


if __name__ == "__main__":
    sys.exit(main())
